#!/usr/bin/env node
// gen-inventory.mjs — the reuse brain's scanner (system-architect SKILL §5, CONTEXT_PROTOCOL §3).
// Scans the project's scan roots for exported symbols + @purpose annotations and writes
// docs/INVENTORY.md so agents reuse/extend instead of rebuilding. Zero dependencies.
// Scan roots come from .claude/stack.json (falls back to packages/apps/src). Currently indexes
// TS/JS exports; other languages get a stub section (extend the matchers as needed).
// Run: node .claude/scripts/gen-inventory.mjs  (regenerate before each fan-out + at close).
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.env.CLAUDE_PROJECT_DIR || process.cwd();
let SCAN_ROOTS = ['packages', 'apps', 'src'];
try {
  const s = JSON.parse(readFileSync(join(ROOT, '.claude/stack.json'), 'utf8'));
  if (Array.isArray(s.scanRoots) && s.scanRoots.length) SCAN_ROOTS = s.scanRoots;
} catch { /* use defaults */ }

const SKIP_DIRS = new Set(['node_modules', 'dist', '.next', 'build', '.turbo', 'coverage', 'venv', '.venv', '__pycache__', 'target', 'vendor']);
const isGenerated = (n) => n === 'database.types.ts' || /\.gen\.(ts|tsx)$/.test(n);
const EXP_DECL = /^export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(const|function|class|type|interface|enum)\s+([A-Za-z0-9_$]+)/;
const EXP_DEFAULT = /^export\s+default\s+(?:async\s+)?(function|class)\s+([A-Za-z0-9_$]+)/;
const EXP_NAMED = /export\s+(?:type\s+)?\{([^}]*)\}/gs; // whole-file, multiline-safe

// Markdown-cell safe: escape pipes/backslashes, flatten newlines, drop backticks.
const escCell = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').replace(/`/g, "'").trim();

function walk(dir, acc = []) {
  let ents;
  try { ents = readdirSync(dir, { withFileTypes: true }); } catch { return acc; }
  for (const e of ents) {
    if (e.name.startsWith('.') || SKIP_DIRS.has(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (/\.(ts|tsx)$/.test(e.name) && !/\.(test|spec|d)\.(ts|tsx)$/.test(e.name) && !isGenerated(e.name)) acc.push(p);
  }
  return acc;
}

function purposeAbove(lines, i) {
  for (let j = i - 1, hops = 0; j >= 0 && hops < 8; j--, hops++) {
    const t = lines[j].trim();
    const m = t.match(/@purpose\s+(.*?)(?:\*\/)?\s*$/);
    if (m) return m[1].trim();
    if (t === '' || t.startsWith('*') || t.startsWith('//') || t.startsWith('/*')) continue;
    break;
  }
  return '';
}

function scanFile(file) {
  let src;
  try { src = readFileSync(file, 'utf8'); }
  catch (e) { console.warn(`gen-inventory: skipped ${file}: ${e.code || e.message}`); return []; }
  const lines = src.split('\n');
  const out = [];
  const seen = new Set();
  const add = (kind, name, purpose) => { if (name && !seen.has(name)) { seen.add(name); out.push({ kind, name, purpose: purpose || '' }); } };
  for (let i = 0; i < lines.length; i++) {
    let m;
    if ((m = lines[i].match(EXP_DEFAULT))) add(`default ${m[1]}`, m[2], purposeAbove(lines, i));
    else if ((m = lines[i].match(EXP_DECL))) add(m[1], m[2], purposeAbove(lines, i));
  }
  let mm; EXP_NAMED.lastIndex = 0;
  while ((mm = EXP_NAMED.exec(src))) {
    for (const raw of mm[1].split(',')) {
      const name = raw.trim().replace(/^type\s+/, '').split(/\s+as\s+/).pop().trim();
      if (/^[A-Za-z0-9_$]+$/.test(name)) add('reexport', name, '');
    }
  }
  return out;
}

function findUnits() {
  const units = [];
  for (const r of SCAN_ROOTS) {
    const base = join(ROOT, r);
    if (!existsSync(base)) continue;
    // If the scan root itself contains code (single-package src/), treat it as one unit.
    let hasSubdirs = false;
    try { hasSubdirs = readdirSync(base, { withFileTypes: true }).some(e => e.isDirectory() && !e.name.startsWith('.') && !SKIP_DIRS.has(e.name)); } catch {}
    if (r === 'src' || !hasSubdirs) { units.push({ pkg: r, dir: base }); continue; }
    for (const e of readdirSync(base, { withFileTypes: true })) {
      if (!e.isDirectory() || e.name.startsWith('.')) continue;
      units.push({ pkg: `${r}/${e.name}`, dir: join(base, e.name) });
    }
  }
  return units;
}

const units = findUnits();
const now = new Date().toISOString().slice(0, 10);
let md = `# INVENTORY.md — reuse map (generated, do not hand-edit)\n\n`;
md += `<!-- generated by .claude/scripts/gen-inventory.mjs on ${now}. Regenerate before every fan-out and at close. -->\n\n`;
md += `> **Reuse rubric:** exact match → **reuse** · close (differs by config) → **extend with a variant/prop** · genuinely new → **create** in the right unit, add a one-line \`@purpose\` comment, regenerate this file. Search here before writing any new component/util/schema, and state your reuse/extend/new choice in the ticket summary.\n\n`;

if (!units.length) {
  md += `_No code under scan roots (${SCAN_ROOTS.join(', ')}) yet — this file is seeded. It auto-fills once code exists._\n\n`;
  md += `**Convention to adopt now:** every shared export carries \`/** @purpose <one line> */\` so this scanner can describe it.\n`;
} else {
  let total = 0;
  for (const u of units) {
    const rows = [];
    for (const f of walk(u.dir)) for (const s of scanFile(f)) rows.push({ ...s, file: relative(ROOT, f) });
    if (!rows.length) continue;
    total += rows.length;
    md += `## ${u.pkg}  _(${rows.length})_\n\n| Export | Kind | Purpose | File |\n|---|---|---|---|\n`;
    for (const r of rows.sort((a, b) => a.name.localeCompare(b.name)))
      md += `| \`${r.name}\` | ${escCell(r.kind)} | ${escCell(r.purpose) || '—'} | \`${r.file}\` |\n`;
    md += `\n`;
  }
  if (!total) md += `_Scan roots exist but no TS/JS exports found. (This scanner indexes TS/JS; add matchers for other languages if needed.)_\n`;
  else md += `\n_${total} exports across ${units.length} unit(s)._\n`;
}

const outDir = join(ROOT, 'docs');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'INVENTORY.md'), md);
console.log(`gen-inventory: ${units.length} unit(s) scanned (roots: ${SCAN_ROOTS.join(', ')}) → docs/INVENTORY.md`);
